local r,g,b,h,s,v,lowH,highH,lowS,highS,lowV,highV;

app.UpdateLowHighHSV = function()
  local epsilon;
  if "high" then epsilon = 0.05;--need the settings for the exactness high/mid/low
  elseif "medium" then epsilon = 0.1;
  elseif "low" then epsilon = 0.2; end
  
  local lowH = h-epsilon;
  if lowH < 0 then lowH = lowH + 1; end
  local highH = h+epsilon;
  if highH < 0 then highH = highH - 1; end
  local lowS = s-epsilon;
  local highS = s+epsilon;
  local lowV = v-epsilon;
  local highV = v+epsilon;
end

app.SetHSVfromRGB = function(rN,gN,bN)
  if rN == r and gN == g and bN == b then return; end
  
  r = rN; g = gN; b = bN;
  
  h,s,v = C_ColorUtil.ConvertRGBToHSV(r,g,b);
  h=h*0.00288;--normalize to 0-1, s and v already normalized 0-1
  
  app.UpdateLowHighHSV();
end

app.SetHSVfromRGBTable = function(tab)
  app.SetHSVfromRGB(tab[1],tab[2],tab[3]);
end

app.CheckSetColorHSV = function(setID, isArmor)
  local colors;
  if isArmor then
    colors = armorColors[setID];
  else
    colors = weaponColors[setID];
  end
  if colors == nil then return false end
  
  for i=1,5 do
    if settings.colorIndex[i] and colors[i] then--need the settings for if using primary,secondary,etc.
      if lowH > highH then
        if colors[i][1] > lowH or colors[i][1] < highH then
          if colors[i][3] > lowV and colors[i][3] < highV then
            if colors[i][2] > lowS and colors[i][2] < highS then
              return true;
            end
          end
        end
      else
        if colors[i][1] > lowH and colors[i][1] < highH then
          if colors[i][3] > lowV and colors[i][3] < highV then
            if colors[i][2] > lowS and colors[i][2] < highS then
              return true;
            end
          end
        end
      end
    end
  end
  return false;
end

app.GetSetColors = function(setID, isArmor)
  if isArmor then
    return armorColors[setID];
  else
    return weaponColors[setID];
  end
end